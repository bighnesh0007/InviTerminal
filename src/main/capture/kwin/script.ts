import { isKwinUuid } from './gvariant';

/**
 * KWin has no Wayland protocol that lets a client exclude itself from
 * capture, but its scripting API exposes Window.excludeFromCapture as a
 * writable property (kwin v6.7.5 window.h:619). The script targets exactly
 * one window by uuid *and* our pid, so it cannot touch another app's windows.
 */
export function buildExclusionScript(target: { uuid: string; pid: number; exclude: boolean }): string {
  if (!isKwinUuid(target.uuid)) throw new Error(`refusing to build script for malformed uuid: ${target.uuid}`);
  if (!Number.isInteger(target.pid) || target.pid <= 0) throw new Error(`invalid pid: ${target.pid}`);
  return `// Generated by InviTerminal. Sets excludeFromCapture on one window owned by pid ${target.pid}.
(function () {
  var target = ${JSON.stringify(target.uuid)};
  var pid = ${target.pid};
  var exclude = ${target.exclude ? 'true' : 'false'};
  var wins = workspace.windowList();
  for (var i = 0; i < wins.length; i++) {
    var w = wins[i];
    if (w.pid === pid && String(w.internalId) === target) {
      w.excludeFromCapture = exclude;
    }
  }
})();
`;
}
